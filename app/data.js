// Discount percentage, rounded to a whole number.
export function pctOff(d) {
  return Math.round((1 - d.price / d.was) * 100);
}

// A plain-language verdict based only on how deep the cut is.
// No price history is claimed unless the deal's `note` says so.
export function verdict(d) {
  const p = pctOff(d);
  if (p >= 50) return "STRONG DEAL";
  if (p >= 30) return "GOOD DEAL";
  if (p >= 20) return "SOLID DEAL";
  return "MODEST";
}

